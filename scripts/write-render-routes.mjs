// Writes render.yaml with a permanent (301) redirect for every old address.
// Run after changing the forwards in src/blog.mjs:  node scripts/write-render-routes.mjs
// Render applies render.yaml automatically (the service is Blueprint managed).
import { writeFile } from "node:fs/promises";
import { blogForwards } from "../src/blog.mjs";

// Rules that were set by hand in the Render dashboard before October 2026.
const earlierRules = {
  "/features/ai": "/event-intelligence",
  "/features/ai/": "/event-intelligence",
  "/ai-insights": "/event-intelligence",
  "/ai-insights/": "/event-intelligence",
  "/features/analyics-and-reports": "/platform",
  "/features/analytics-and-reports": "/platform",
  "/features/event-communications": "/event-communications-platform",
  "/features/branded-event-web-and-emails": "/white-label-event-platform",
  "/features/event-surveys": "/event-analytics-reporting",
  "/analytics": "/event-analytics-reporting",
  "/whitelabel-overview": "/white-label-event-platform",
  "/price-plans": "/pricing",
};

const all = { ...earlierRules, ...blogForwards };
const quote = (text) => JSON.stringify(text);
const routes = Object.entries(all)
  .map(([source, destination]) => `      - type: redirect\n        source: ${quote(source)}\n        destination: ${quote(destination)}`)
  .join("\n");

await writeFile(
  new URL("../render.yaml", import.meta.url),
  `# Render Blueprint for the Mitingu website (static site)
# Docs: https://render.com/docs/blueprint-spec
# The routes list is generated by scripts/write-render-routes.mjs: edit the
# forwards in src/blog.mjs, then run that script, rather than editing by hand.
services:
  - type: web
    name: mitingu-website
    runtime: static
    buildCommand: npm run build
    staticPublishPath: ./dist/client
    routes:
${routes}
`,
);
console.log(`render.yaml: ${Object.keys(all).length} redirects`);
